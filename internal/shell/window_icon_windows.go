//go:build windows

package shell

import (
	"errors"
	"fmt"
	"os"
	"unsafe"

	"golang.org/x/sys/windows"
)

const (
	WindowClassName = "ElasticDefendConsoleWindow"
	ApplicationID   = "ElasticUI.DefendConsole"
)

// SetApplicationIdentity must run before any application windows are created.
// A stable explicit identity keeps the taskbar group separate from Wails defaults.
func SetApplicationIdentity() error {
	id, err := windows.UTF16PtrFromString(ApplicationID)
	if err != nil {
		return err
	}
	hr, _, _ := windows.NewLazySystemDLL("shell32.dll").NewProc("SetCurrentProcessExplicitAppUserModelID").Call(uintptr(unsafe.Pointer(id)))
	if int32(hr) < 0 {
		return fmt.Errorf("set application identity: HRESULT 0x%08x", uint32(hr))
	}
	return nil
}

// SetWindowIcons sets both WM_SETICON slots. Wails only sets ICON_SMALL;
// ICON_BIG can otherwise fall back to the window class's default Wails icon.
// The shared resource handles remain valid for the lifetime of the process.
func SetWindowIcons(className string) error {
	user32 := windows.NewLazySystemDLL("user32.dll")
	module, _, err := windows.NewLazySystemDLL("kernel32.dll").NewProc("GetModuleHandleW").Call(0)
	if module == 0 {
		return fmt.Errorf("get application module: %w", err)
	}
	var result error
	found := false
	callback := windows.NewCallback(func(hwnd, _ uintptr) uintptr {
		var pid uint32
		user32.NewProc("GetWindowThreadProcessId").Call(hwnd, uintptr(unsafe.Pointer(&pid)))
		if pid != uint32(os.Getpid()) {
			return 1
		}
		var name [256]uint16
		user32.NewProc("GetClassNameW").Call(hwnd, uintptr(unsafe.Pointer(&name[0])), uintptr(len(name)))
		if windows.UTF16ToString(name[:]) != className {
			return 1
		}
		found = true
		dpi, _, _ := user32.NewProc("GetDpiForWindow").Call(hwnd)
		if dpi == 0 {
			dpi = 96
		}
		// SM_CXICON/SM_CYICON for ICON_BIG; SM_CXSMICON/SM_CYSMICON for ICON_SMALL.
		for _, slot := range []struct{ kind, width, height uintptr }{{1, 11, 12}, {0, 49, 50}} {
			width, _, _ := user32.NewProc("GetSystemMetricsForDpi").Call(slot.width, dpi)
			height, _, _ := user32.NewProc("GetSystemMetricsForDpi").Call(slot.height, dpi)
			// Resource 3 is generated by Wails from build/windows/icon.ico.
			icon, _, loadErr := user32.NewProc("LoadImageW").Call(module, 3, 1, width, height, 0x8000)
			if icon == 0 {
				result = fmt.Errorf("load window icon %d: %w", slot.kind, loadErr)
				return 0
			}
			user32.NewProc("SendMessageW").Call(hwnd, 0x80, slot.kind, icon)
			index := ^uintptr(13) // GCLP_HICON (-14)
			if slot.kind == 0 {
				index = ^uintptr(33) // GCLP_HICONSM (-34)
			}
			user32.NewProc("SetClassLongPtrW").Call(hwnd, index, icon)
		}
		return 1
	})
	user32.NewProc("EnumWindows").Call(callback, 0)
	if result != nil {
		return result
	}
	if !found {
		return errors.New("application window not found")
	}
	return nil
}
