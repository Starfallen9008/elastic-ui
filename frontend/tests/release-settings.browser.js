(async () => {
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const until = async fn => { for (let i=0;i<160;i++) { if (fn()) return; await pause(25); } throw Error('UI timed out'); };
  const clickText = (selector,text) => { const button=[...document.querySelectorAll(selector)].find(b=>b.textContent.trim()===text); assert(button,'Missing '+text); button.click(); };
  const app = window.go.main.App;
  let startup=false, startupCalls=0, checks=0;
  app.StartupEnabled=async()=>startup;
  app.SetStartupEnabled=async value=>{ startupCalls++; startup=value; };
  app.CheckUpdate=async()=>{ checks++; return {version: checks===1?'1.0.0':'1.0.1',available:checks>1,notes:'fixture'}; };
  await until(()=>document.querySelector('.position-settings'));
  document.querySelector('.position-settings').click();
  await until(()=>document.querySelector('[aria-label="开机自启"]'));
  document.querySelector('[aria-label="开机自启"]').click();
  await until(()=>document.querySelector('[aria-label="开机自启"]').getAttribute('aria-pressed')==='true');
  assert(startupCalls===1,'startup submitted twice');
  clickText('button','检查更新');
  await until(()=>document.querySelector('.update-row').textContent.includes('已是最新版本'));
  clickText('button','检查更新');
  await until(()=>document.querySelector('.update-row').textContent.includes('v1.0.1'));
  assert([...document.querySelectorAll('button')].some(b=>b.textContent==='更新并重启'),'update action missing');
  const missing={id:'missing',path:'C:\\Downloads\\missing.exe',sha256:'b'.repeat(64),quarantinePath:'C:\\.equarantine\\missing',outcome:'已隔离',recoverable:false,availability:'missing',trustStatus:'configured',savedPath:'D:\\recovered.zip',recoveredAt:'2026-11-20T12:00:00Z'};
  app.GetQuarantine=async()=>({total:1,items:[missing]});
  clickText('button','隔离区');
  await until(()=>document.querySelector('.file-row'));
  assert(document.querySelector('.file-row').textContent.includes('隔离文件已不存在'),'missing state hidden');
  assert([...document.querySelectorAll('.file-row .actions button')].every(b=>b.disabled),'missing recovery or configured trust enabled');
  assert(document.querySelector('.file-row').textContent.includes(missing.savedPath),'saved location lost');
  document.querySelector('[aria-label="关闭扫描结果"]').click();
  document.querySelector('.back-btn').click();
  await until(()=>!document.querySelector('.back-btn'));
  const toggle=document.querySelector('[aria-label*="主题"]') || document.querySelector('[title*="主题"]');
  assert(toggle,'theme toggle missing');
  const before=document.documentElement.dataset.theme;
  let transitions=0;
  const original=document.startViewTransition?.bind(document);
  if (original) document.startViewTransition=callback=>{ transitions++; return original(callback); };
  toggle.click();
  await until(()=>document.documentElement.dataset.theme!==before);
  assert(transitions===1 || matchMedia('(prefers-reduced-motion: reduce)').matches || document.documentElement.classList.contains('theme-changing'),'theme has no transition');
  await pause(350);
  assert(document.documentElement.scrollWidth<=innerWidth,'page horizontal overflow');
  return {passed:true,viewport:[innerWidth,innerHeight],startupCalls,checks,themeTransitions:transitions};
})()
